#!/usr/bin/env python3
"""Build the CF_ROM_SYNC reference image.

The layout is the customer-facing map in docs/rom_image_map.md.
Address 0 and each single-bit address must hold a distinct byte so a
stuck address line cannot hide inside a repeated pattern.
"""

from __future__ import annotations

import argparse
import hashlib
import math
import zlib
from pathlib import Path

DEPTH = 1024
FINGERPRINT_ADDRS = (0, 1, 2, 4, 8, 16, 32, 64, 128, 256, 512)
BANNER = b"CF_ROM_SYNC reference image v1"


def sine_sample(index: int) -> int:
    return int(round(32767 * math.sin(2 * math.pi * index / 64)))


def build_image() -> bytes:
    img = bytearray(DEPTH)

    for addr in range(0x020, 0x060):
        row = (addr - 0x020) // 16
        nibble = (addr & 1) == 0
        if row % 2 == 0:
            img[addr] = 0x55 if nibble else 0xAA
        else:
            img[addr] = 0xAA if nibble else 0x55

    for addr in range(0x060, 0x080):
        img[addr] = 0x00
    for addr in range(0x080, 0x100):
        img[addr] = 0xFF
    for addr in range(0x100, 0x200):
        img[addr] = addr & 0xFF
    for addr in range(0x200, 0x300):
        img[addr] = (~(addr & 0xFF)) & 0xFF

    for index in range(64):
        sample = sine_sample(index) & 0xFFFF
        img[0x300 + 2 * index] = sample & 0xFF
        img[0x300 + 2 * index + 1] = (sample >> 8) & 0xFF

    banner = BANNER + b"\x00"
    if len(banner) > 64:
        raise SystemExit("banner does not fit in 0x380-0x3BF")
    img[0x380:0x380 + len(banner)] = banner

    for addr in range(0x3C0, 0x3FC):
        img[addr] = 0xFF

    walking_ones = (0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01)
    walking_zeros = tuple((~b) & 0xFF for b in walking_ones)
    img[0x010:0x018] = bytes(walking_ones)
    img[0x018:0x020] = bytes(walking_zeros)

    img[0x000:0x010] = bytes(
        (
            0x43, 0x46, 0x52, 0x4D,
            0x01, 0x00, 0x00, 0x04,
            0x10, 0x18, 0x20, 0x60,
            0x80, 0x00, 0x01, 0x00,
        )
    )

    # Break two repeated-pattern collisions. Tests expect these bytes.
    img[0x040] = 0x5A
    img[0x200] = 0xA5

    digest = zlib.crc32(bytes(img[:0x3FC])) & 0xFFFFFFFF
    img[0x3FC] = digest & 0xFF
    img[0x3FD] = (digest >> 8) & 0xFF
    img[0x3FE] = (digest >> 16) & 0xFF
    img[0x3FF] = (digest >> 24) & 0xFF

    seen = [img[addr] for addr in FINGERPRINT_ADDRS]
    if len(set(seen)) != len(seen):
        raise SystemExit("address fingerprint is not unique: %s" % seen)
    return bytes(img)


def image_crc(image: bytes) -> int:
    return int.from_bytes(image[0x3FC:0x400], "little")


def write_hex(path: Path, image: bytes) -> None:
    path.write_text("".join("%02x\n" % byte for byte in image))


def write_header(path: Path, image: bytes) -> None:
    crc = image_crc(image)
    lines = [
        "/* Generated by rom/gen_rom_image.py. Do not edit. */",
        "#ifndef ROM_MAP_H",
        "#define ROM_MAP_H",
        "",
        "#define ROM_IMAGE_BYTES 1024u",
        "#define ROM_IMAGE_CRC 0x%08Xu" % crc,
        "#define ROM_SINE_0 %d" % sine_sample(0),
        "#define ROM_SINE_16 %d" % sine_sample(16),
        "#define ROM_SINE_48 (%d)" % sine_sample(48),
        "#define ROM_MAGIC_WORD 0x4346524Du",
        "",
        "#endif",
        "",
    ]
    path.write_text("\n".join(lines))


def write_python(path: Path, image: bytes) -> None:
    crc = image_crc(image)
    digest = hashlib.sha256(image).hexdigest()
    body = ",\n".join("    0x%02X" % byte for byte in image)
    text = (
        '"""Generated by rom/gen_rom_image.py. Do not edit."""\n\n'
        "CRC32 = 0x%08X\n" % crc
        + 'SHA256 = "%s"\n' % digest
        + "IMAGE = bytes((\n"
        + body
        + "\n))\n"
    )
    path.write_text(text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hex", required=True)
    parser.add_argument("--header", required=True)
    parser.add_argument("--python", required=True)
    args = parser.parse_args(argv)
    image = build_image()
    for dest in (args.hex, args.header, args.python):
        Path(dest).parent.mkdir(parents=True, exist_ok=True)
    write_hex(Path(args.hex), image)
    write_header(Path(args.header), image)
    write_python(Path(args.python), image)
    print("image %d crc %08x" % (len(image), image_crc(image)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
